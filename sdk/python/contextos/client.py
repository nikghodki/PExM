"""
ContextOS Python SDK — gRPC client.

Usage::

    from contextos import ContextOSClient, MemoryTier, Scope

    client = ContextOSClient("localhost:50051")
    entry_id = client.memory.store(
        agent_id="agent-001",  # human-readable IDs are auto-converted to UUIDs
        content="The refactor moves auth logic to middleware.py",
        tier=MemoryTier.L2_TASK,
        scope=Scope.TEAM,
    )
    entry = client.memory.get(entry_id)

Note: This client wraps the raw gRPC stubs generated by grpcio-tools.
Run `make proto-python` from the repo root to regenerate the stubs.
"""

