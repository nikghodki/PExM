# ── UUID coercion ─────────────────────────────────────────────────────────────

_CONTEXTOS_NS = uuid.UUID("6ba7b810-9dad-11d1-80b4-00c04fd430c8")  # UUID namespace

def _coerce_uuid(value: str) -> str:
    """Accept either a valid UUID string or any human-readable ID.

    Human-readable strings (e.g. ``"agent-001"``) are deterministically mapped
    to a UUID5 so the same string always produces the same UUID.  Valid UUID
    strings pass through unchanged.
    """
    try:
        return str(uuid.UUID(value))
    except ValueError:
        return str(uuid.uuid5(_CONTEXTOS_NS, value))


def _ts(ts) -> Optional[datetime]:
    """Convert a proto ``Timestamp`` to a Python datetime, or None if unset."""
    if ts is None:
        return None
    # A default-constructed Timestamp (no value) is not "set" in proto3 terms.
    if ts.seconds == 0 and ts.nanos == 0:
        return None
    return ts.ToDatetime()

class _MemoryClient:
    """High-level wrapper around the MemoryService gRPC stub."""

    def __init__(self, channel: grpc.Channel) -> None:
        self._channel = channel
        # Stub is imported lazily so the SDK can be imported without generated code
        self._stub: Optional[object] = None

    def _get_stub(self):
        if self._stub is None:
            try:
                from contextos.proto import memory_pb2_grpc  # type: ignore
                self._stub = memory_pb2_grpc.MemoryServiceStub(self._channel)
            except ImportError as e:
                raise RuntimeError(
                    "Proto stubs not found. Run `make proto-python` to generate them."
                ) from e
        return self._stub

    def store(
        self,
        agent_id: str,
        content: str,
        tier: MemoryTier = MemoryTier.L1_SESSION,
        scope: Scope = Scope.PRIVATE,
        tags: list[str] | None = None,
        metadata: dict[str, str] | None = None,
    ) -> str:
        """Store a memory entry and return its ID."""
        from contextos.proto import memory_pb2  # type: ignore
        req = memory_pb2.StoreMemoryRequest(
            agent_id = _coerce_uuid(agent_id),
            content  = content,
            tier     = tier.value,
            scope    = scope.value,
            tags     = tags or [],
        )
        if metadata:
            req.metadata.update(metadata)
        resp = self._get_stub().StoreMemory(req)
        return resp.id

    def get(self, memory_id: str) -> Optional[MemoryEntry]:
        """Retrieve a memory entry by ID, or None if not found."""
        from contextos.proto import memory_pb2  # type: ignore
        req  = memory_pb2.GetMemoryRequest(id=memory_id)
        resp = self._get_stub().GetMemory(req)
        if not resp.HasField("entry"):
            return None
        e = resp.entry
        return MemoryEntry(
            id         = e.id,
            agent_id   = e.agent_id,
            content    = e.content,
            tier       = MemoryTier(e.tier),
            scope      = Scope(e.scope),
            score      = e.score,
            tags       = list(e.tags),
            metadata   = dict(e.metadata),
            created_at = _ts(e.created_at),
            accessed_at= _ts(e.accessed_at),
            expires_at = _ts(e.expires_at),
        )

    def search(
        self,
        agent_id: str,
        query: str,
        top_k: int = 10,
        scope: Scope | None = None,
    ) -> list[MemoryEntry]:
        """Semantic search across memories.

        ``scope=None`` (default) searches across all scopes.
        Pass a specific :class:`Scope` to restrict results.
        """
        from contextos.proto import memory_pb2  # type: ignore
        req  = memory_pb2.SearchMemoryRequest(
            agent_id = _coerce_uuid(agent_id),
            query    = query,
            top_k    = top_k,
            scope    = scope.value if scope is not None else 0,
        )
        resp = self._get_stub().SearchMemory(req)
        return [
            MemoryEntry(
                id      = e.id,
                agent_id= e.agent_id,
                content = e.content,
                tier    = MemoryTier(e.tier),
                scope   = Scope(e.scope),
                score   = e.score,
            )
            for e in resp.results
        ]

    def delete(self, memory_id: str) -> bool:
        from contextos.proto import memory_pb2  # type: ignore
        resp = self._get_stub().DeleteMemory(memory_pb2.DeleteMemoryRequest(id=memory_id))
        return resp.ok

    def promote(self, memory_id: str, target_tier: MemoryTier) -> MemoryTier:
        """Promote a memory to a higher tier and return the resulting tier."""
        from contextos.proto import memory_pb2  # type: ignore
        req  = memory_pb2.PromoteMemoryRequest(id=memory_id, target_tier=target_tier.value)
        resp = self._get_stub().PromoteMemory(req)
        if not resp.ok:
            raise RuntimeError(f"PromoteMemory failed for {memory_id}")
        return MemoryTier(resp.new_tier)

    def list(
        self,
        agent_id: str,
        tier: MemoryTier | None = None,
        scope: Scope | None = None,
        page_size: int = 50,
    ) -> list[MemoryEntry]:
        """List memories for an agent, optionally filtered by tier/scope."""
        from contextos.proto import memory_pb2  # type: ignore
        req = memory_pb2.ListMemoriesRequest(
            agent_id   = _coerce_uuid(agent_id),
            tier       = tier.value if tier is not None else 0,
            scope      = scope.value if scope is not None else 0,
            page_size  = page_size,
        )
        resp = self._get_stub().ListMemories(req)
        return [
            MemoryEntry(
                id      = e.id,
                agent_id= e.agent_id,
                content = e.content,
                tier    = MemoryTier(e.tier),
                scope   = Scope(e.scope),
                score   = e.score,
                tags    = list(e.tags),
                metadata= dict(e.metadata),
            )
            for e in resp.entries
        ]


class _IndexerClient:
    def __init__(self, channel: grpc.Channel) -> None:
        self._channel = channel

    def _get_stub(self):
        from contextos.proto import indexer_pb2_grpc  # type: ignore
        return indexer_pb2_grpc.IndexerServiceStub(self._channel)

    def index_repo(
        self, repo_id: str, local_path: str, languages: list[str], incremental: bool = False
    ) -> dict:
        from contextos.proto import indexer_pb2  # type: ignore
        req  = indexer_pb2.IndexRepositoryRequest(
            repo_id    = repo_id,
            local_path = local_path,
            languages  = languages,
            incremental= incremental,
        )
        resp = self._get_stub().IndexRepository(req)
        return {"ok": resp.ok, "symbols_added": resp.symbols_added, "duration_ms": resp.duration_ms}

    def query_symbols(self, repo_id: str, query: str, top_k: int = 10) -> list[SymbolNode]:
        from contextos.proto import indexer_pb2  # type: ignore
        req  = indexer_pb2.QuerySymbolsRequest(repo_id=repo_id, query=query, top_k=top_k)
        resp = self._get_stub().QuerySymbols(req)
        return [
            SymbolNode(
                id             = s.id,
                repo_id        = s.repo_id,
                file_path      = s.file_path,
                name           = s.name,
                qualified_name = s.qualified_name,
                kind           = SymbolKind(s.kind),
                start_line     = s.start_line,
                end_line       = s.end_line,
            )
            for s in resp.results
        ]

    def _to_symbol(self, s) -> SymbolNode:
        """Map a proto SymbolNode to the SDK dataclass."""
        return SymbolNode(
            id             = s.id,
            repo_id        = s.repo_id,
            file_path      = s.file_path,
            name           = s.name,
            qualified_name = s.qualified_name,
            kind           = SymbolKind(s.kind),
            start_line     = s.start_line,
            end_line       = s.end_line,
            signature      = s.signature,
            docstring      = s.docstring,
            callers        = list(s.callers),
            callees        = list(s.callees),
            deps           = list(s.deps),
            metadata       = dict(s.metadata),
        )

    def get_symbol(self, symbol_id: str) -> Optional[SymbolNode]:
        from contextos.proto import indexer_pb2  # type: ignore
        req  = indexer_pb2.GetSymbolRequest(id=symbol_id)
        resp = self._get_stub().GetSymbol(req)
        if not resp.HasField("symbol"):
            return None
        return self._to_symbol(resp.symbol)

    def get_commit_diff(self, repo_id: str, commit_sha: str) -> Optional[CommitDiff]:
        from contextos.proto import indexer_pb2  # type: ignore
        req  = indexer_pb2.GetCommitDiffRequest(repo_id=repo_id, commit_sha=commit_sha)
        resp = self._get_stub().GetCommitDiff(req)
        if not resp.HasField("diff"):
            return None
        d = resp.diff
        return CommitDiff(
            repo_id    = d.repo_id,
            commit_sha = d.commit_sha,
            author     = d.author,
            message    = d.message,
            timestamp  = datetime.fromtimestamp(d.timestamp) if d.timestamp else None,
            files      = [
                FileDiff(
                    path         = f.path,
                    added_lines  = f.added_lines,
                    removed_lines= f.removed_lines,
                    old_content  = f.old_content,
                    new_content  = f.new_content,
                )
                for f in d.files
            ],
        )

    def query_function_deltas(self, function_id: str, limit: int = 10) -> list[dict]:
        """Return recent deltas (old/new body + linked tests) for a function."""
        from contextos.proto import indexer_pb2  # type: ignore
        req  = indexer_pb2.QueryFunctionDeltasRequest(function_id=function_id, limit=limit)
        resp = self._get_stub().QueryFunctionDeltas(req)
        return [
            {
                "function_id": d.function_id,
                "commit_sha":  d.commit_sha,
                "old_body":    d.old_body,
                "new_body":    d.new_body,
                "linked_test_ids": list(d.linked_test_ids),
            }
            for d in resp.deltas
        ]


